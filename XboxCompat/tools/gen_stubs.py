"""Generate traced-stub sources for Xbox-only imports of game_scarlett_master.exe.

Input : docs/research/data/exe_pe.json (pescan output of the exe)
Output: XboxCompat/generated/<dll>_stubs.cpp for pure-stub DLLs, and XboxCompat/generated/<dll>_missing.inc for DLLs that
        also have hand-written functions (xmem, d3d12_xs). Functions that are implemented by hand are listed in IMPLEMENTED.
Only names found in the exe's import table are generated; nothing is invented.
Run: python -I gen_stubs.py <exe_pe.json> <XboxCompat dir>
"""
import json, os, sys

exe_json, root = sys.argv[1], sys.argv[2]
imports = json.load(open(exe_json))['game_scarlett_master.exe']['imports']

STUB_DLLS = ['xg_xs.dll', 'chad.dll', 'xapu.dll', 'AcpHal.dll', 'XCRDAPI.dll']
MIXED_DLLS = {'xmem.dll': {'XMemAlloc', 'XMemFree', 'XMemVirtualQuery', 'XMemGetWorkingSetStatistics',
                           'XMemVirtualAlloc', 'XMemAllocatePhysicalPages', 'XMemMapPhysicalPages',
                           'XMemMapPhysicalPagesScatter', 'XMemFreePhysicalPages'},
              'd3d12_xs.dll': {'D3D12SerializeVersionedRootSignature', 'D3D12CreateRootSignatureDeserializer',
                               'D3D12XboxCreateDevice', 'D3D12ConfigureVirtualMemoryX'}}
# Names implemented by dedicated hand-written code in other files (not stubs):
EXTRA_IMPLEMENTED = {'d3d12_xs.dll': set()}

out = os.path.join(root, 'generated')
os.makedirs(out, exist_ok=True)
manifest = {}
for dll in STUB_DLLS:
    names = sorted(imports[dll])
    mod = dll[:-4]
    with open(os.path.join(out, f'{mod}_stubs.cpp'), 'w', encoding='utf-8') as f:
        f.write(f'// GENERATED by tools/gen_stubs.py from the exe import table. Do not edit; replace stubs in dedicated files.\n')
        f.write('#include "xc_stub.h"\n\n')
        for n in names:
            f.write(f'XC_STUB("{mod}", {n})\n')
        f.write('\nBOOL APIENTRY DllMain(HMODULE, DWORD, LPVOID) { return TRUE; }\n')
    manifest[dll] = names
for dll, implemented in MIXED_DLLS.items():
    mod = dll[:-4]
    names = sorted(n for n in imports[dll] if n not in implemented and not n.startswith('ord'))
    with open(os.path.join(out, f'{mod}_missing.inc'), 'w', encoding='utf-8') as f:
        f.write('// GENERATED by tools/gen_stubs.py: exe imports not yet implemented by hand.\n')
        for n in names:
            f.write(f'XC_STUB("{mod}", {n})\n')
    manifest[dll + ' (missing, stubbed)'] = names
json.dump(manifest, open(os.path.join(out, 'manifest.json'), 'w'), indent=1)
print(json.dumps(manifest, indent=1))
